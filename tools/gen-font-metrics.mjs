// Generates site/js/core/fontmetrics-data.js from the vendored TTFs.
// Reads cmap (format 4), hmtx, head, hhea and OS/2 so text can be measured
// identically in the browser preview, the PDF backend and Node tests.
// Usage: node tools/gen-font-metrics.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = {
  regular: 'site/fonts/AtkinsonHyperlegible-Regular.ttf',
  bold: 'site/fonts/AtkinsonHyperlegible-Bold.ttf',
};

// Codepoints we support in text: printable ASCII, Latin-1 supplement, and a few typographic extras.
const EXTRA = [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x00b7, 0x2192, 0x2190, 0x2191, 0x2193, 0x2713, 0x00d7, 0x2605, 0x2606, 0x25cf, 0x25cb, 0x2665];

function parse(buf) {
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  const numTables = dv.getUint16(4);
  const tables = {};
  for (let i = 0; i < numTables; i++) {
    const o = 12 + i * 16;
    const tag = String.fromCharCode(dv.getUint8(o), dv.getUint8(o + 1), dv.getUint8(o + 2), dv.getUint8(o + 3));
    tables[tag] = { offset: dv.getUint32(o + 8), length: dv.getUint32(o + 12) };
  }
  const head = tables.head.offset;
  const unitsPerEm = dv.getUint16(head + 18);
  const hhea = tables.hhea.offset;
  const ascender = dv.getInt16(hhea + 4);
  const descender = dv.getInt16(hhea + 6);
  const lineGap = dv.getInt16(hhea + 8);
  const numberOfHMetrics = dv.getUint16(hhea + 34);
  const os2 = tables['OS/2'].offset;
  const os2version = dv.getUint16(os2);
  const capHeight = os2version >= 2 ? dv.getInt16(os2 + 88) : Math.round(ascender * 0.7);
  const xHeight = os2version >= 2 ? dv.getInt16(os2 + 86) : Math.round(ascender * 0.5);

  const hmtx = tables.hmtx.offset;
  const advance = (gid) => dv.getUint16(hmtx + 4 * Math.min(gid, numberOfHMetrics - 1));

  // cmap: find platform 3 / encoding 1 (or 0/3) format 4 subtable
  const cmap = tables.cmap.offset;
  const nSub = dv.getUint16(cmap + 2);
  let sub = -1;
  for (let i = 0; i < nSub; i++) {
    const p = dv.getUint16(cmap + 4 + i * 8), e = dv.getUint16(cmap + 6 + i * 8), off = dv.getUint32(cmap + 8 + i * 8);
    if (dv.getUint16(cmap + off) === 4 && ((p === 3 && e === 1) || p === 0)) { sub = cmap + off; break; }
  }
  if (sub < 0) throw new Error('no format-4 cmap');
  const segX2 = dv.getUint16(sub + 6);
  const endO = sub + 14, startO = endO + segX2 + 2, deltaO = startO + segX2, rangeO = deltaO + segX2;
  function glyphId(cp) {
    for (let s = 0; s < segX2 / 2; s++) {
      const end = dv.getUint16(endO + s * 2);
      if (cp > end) continue;
      const start = dv.getUint16(startO + s * 2);
      if (cp < start) return 0;
      const delta = dv.getInt16(deltaO + s * 2);
      const ro = dv.getUint16(rangeO + s * 2);
      if (ro === 0) return (cp + delta) & 0xffff;
      const g = dv.getUint16(rangeO + s * 2 + ro + (cp - start) * 2);
      return g === 0 ? 0 : (g + delta) & 0xffff;
    }
    return 0;
  }
  const widths = {};
  const cps = [];
  for (let c = 0x20; c <= 0x7e; c++) cps.push(c);
  for (let c = 0xa0; c <= 0xff; c++) cps.push(c);
  cps.push(...EXTRA);
  const missing = [];
  for (const cp of cps) {
    const g = glyphId(cp);
    if (g === 0) { missing.push(cp); continue; }
    widths[cp] = advance(g);
  }
  return { unitsPerEm, ascender, descender, lineGap, capHeight, xHeight, widths, missing, notdef: advance(0) };
}

const out = {};
for (const [k, p] of Object.entries(FONTS)) {
  const m = parse(readFileSync(join(root, p)));
  if (m.missing.length) console.log(`${k}: missing glyphs for`, m.missing.map((c) => 'U+' + c.toString(16).toUpperCase().padStart(4, '0')).join(' '));
  out[k] = m;
}

const js = `// GENERATED by tools/gen-font-metrics.mjs — do not edit by hand.
// Advance widths in font units for Atkinson Hyperlegible (OFL). Keys are Unicode codepoints.
export const FONT_DATA = ${JSON.stringify(
  Object.fromEntries(Object.entries(out).map(([k, m]) => [k, {
    unitsPerEm: m.unitsPerEm, ascender: m.ascender, descender: m.descender, lineGap: m.lineGap,
    capHeight: m.capHeight, xHeight: m.xHeight, notdef: m.notdef, widths: m.widths,
    supported: Object.keys(m.widths).map(Number),
  }]))
)};
`;
writeFileSync(join(root, 'site/js/core/fontmetrics-data.js'), js);
console.log('wrote site/js/core/fontmetrics-data.js', Object.keys(out.regular.widths).length, 'glyphs; upm', out.regular.unitsPerEm);
